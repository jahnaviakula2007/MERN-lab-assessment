// Export Arithmetic Functions
export function addValues(firstNumber, secondNumber) {
    return firstNumber + secondNumber;
}
export function subtractValues(firstNumber, secondNumber) {
    return firstNumber - secondNumber;
}
export function multiplyValues(firstNumber, secondNumber) {
    return firstNumber * secondNumber;
}
export function divideValues(firstNumber, secondNumber) {
    return firstNumber / secondNumber;
}
