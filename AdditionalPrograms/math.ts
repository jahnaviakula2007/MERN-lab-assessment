// Export Arithmetic Functions

export function addValues(firstNumber: number, secondNumber: number): number {
    return firstNumber + secondNumber;
}

export function subtractValues(firstNumber: number, secondNumber: number): number {
    return firstNumber - secondNumber;
}

export function multiplyValues(firstNumber: number, secondNumber: number): number {
    return firstNumber * secondNumber;
}

export function divideValues(firstNumber: number, secondNumber: number): number {
    return firstNumber / secondNumber;
}